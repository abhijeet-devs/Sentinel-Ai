router = APIRouter(prefix="/api/reports", tags=["Reports"])

DARK_BG = colors.HexColor("#0d1117")
CYAN = colors.HexColor("#00d4ff")
GREEN = colors.HexColor("#10b981")
RED = colors.HexColor("#ef4444")
ORANGE = colors.HexColor("#f59e0b")
PURPLE = colors.HexColor("#a855f7")
LIGHT_GRAY = colors.HexColor("#f0f6fc")
MID_GRAY = colors.HexColor("#8b949e")
DARK_PANEL = colors.HexColor("#161b22")
BORDER = colors.HexColor("#30363d")


def severity_color(score: float):
    if score >= 80: return RED
    if score >= 60: return ORANGE
    if score >= 40: return colors.HexColor("#fbbf24")
    if score >= 20: return GREEN
    return CYAN


def severity_label(score: float) -> str:
    if score >= 80: return "CRITICAL"
    if score >= 60: return "HIGH"
    if score >= 40: return "MODERATE"
    if score >= 20: return "LOW"
    return "MINIMAL"


def build_pdf_report(analyses: list, user: User, report_type: str = "full") -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        rightMargin=1.5*cm,
        leftMargin=1.5*cm,
        topMargin=2*cm,
        bottomMargin=2*cm,
    )

    styles = getSampleStyleSheet()
    story = []

    # ─── Title Block ─────────────────────────────────────────────────
    title_style = ParagraphStyle('Title', parent=styles['Normal'],
        fontSize=22, textColor=CYAN, spaceAfter=4, alignment=TA_CENTER, fontName='Helvetica-Bold')
    sub_style = ParagraphStyle('Sub', parent=styles['Normal'],
        fontSize=10, textColor=MID_GRAY, spaceAfter=2, alignment=TA_CENTER)
    body_style = ParagraphStyle('Body', parent=styles['Normal'],
        fontSize=9, textColor=LIGHT_GRAY, leading=14)
    label_style = ParagraphStyle('Label', parent=styles['Normal'],
        fontSize=7.5, textColor=MID_GRAY, fontName='Helvetica', spaceAfter=2)
    mono_style = ParagraphStyle('Mono', parent=styles['Normal'],
        fontSize=8, fontName='Courier', textColor=CYAN, leading=12)
    section_style = ParagraphStyle('Section', parent=styles['Normal'],
        fontSize=11, textColor=CYAN, fontName='Helvetica-Bold', spaceBefore=12, spaceAfter=6)

    story.append(Paragraph("SENTINEL-AI", title_style))
    story.append(Paragraph("Intelligent Prompt Detection &amp; Defence Framework", sub_style))
    story.append(Paragraph("FORENSIC SECURITY AUDIT REPORT", sub_style))
    story.append(Spacer(1, 8))
    story.append(HRFlowable(width="100%", thickness=1, color=CYAN))
    story.append(Spacer(1, 10))

    # ─── Report Metadata ──────────────────────────────────────────────
    meta_rows = [
        ["Report Type", report_type.upper()],
        ["Generated By", user.username],
        ["Generated At", datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")],
        ["Total Incidents", str(len(analyses))],
        ["Threats Detected", str(sum(1 for a in analyses if a.is_malicious))],
        ["Safe Prompts", str(sum(1 for a in analyses if not a.is_malicious))],
    ]
    meta_table = Table(meta_rows, colWidths=[4*cm, 12*cm])
    meta_table.setStyle(TableStyle([
        ('TEXTCOLOR', (0, 0), (-1, -1), LIGHT_GRAY),
        ('TEXTCOLOR', (0, 0), (0, -1), MID_GRAY),
        ('FONTNAME', (0, 0), (0, -1), 'Helvetica'),
        ('FONTNAME', (1, 0), (1, -1), 'Courier'),
        ('FONTSIZE', (0, 0), (-1, -1), 8.5),
        ('ROWBACKGROUNDS', (0, 0), (-1, -1), [DARK_PANEL, DARK_BG]),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ('LEFTPADDING', (0, 0), (-1, -1), 8),
        ('BOX', (0, 0), (-1, -1), 0.5, BORDER),
        ('INNERGRID', (0, 0), (-1, -1), 0.25, BORDER),
    ]))
    story.append(meta_table)
    story.append(Spacer(1, 14))

    # ─── Summary Statistics ───────────────────────────────────────────
    threats = [a for a in analyses if a.is_malicious]
    if threats:
        avg_sev = sum(a.severity_score for a in threats) / len(threats)
        story.append(Paragraph("Executive Summary", section_style))
        story.append(HRFlowable(width="100%", thickness=0.5, color=BORDER))
        story.append(Spacer(1, 6))

        threat_rate = len(threats) / len(analyses) * 100 if analyses else 0
        attack_types = {}
        for a in threats:
            key = a.attack_type or "Unknown"
            attack_types[key] = attack_types.get(key, 0) + 1

        summary_text = (
            f"This report covers <b>{len(analyses)}</b> prompt analysis records generated by the SentinelAI "
            f"detection engine. Of these, <b>{len(threats)}</b> ({threat_rate:.1f}%) were classified as "
            f"malicious with an average severity score of <b>{avg_sev:.1f}/100</b>. "
            f"The dominant attack category was <b>{max(attack_types, key=attack_types.get) if attack_types else 'N/A'}</b>."
        )
        p = ParagraphStyle('SummaryBody', parent=body_style, textColor=LIGHT_GRAY, fontSize=9)
        story.append(Paragraph(summary_text, p))
        story.append(Spacer(1, 10))

    # ─── Incident Records ─────────────────────────────────────────────
    story.append(Paragraph("Incident Records", section_style))
    story.append(HRFlowable(width="100%", thickness=0.5, color=BORDER))
    story.append(Spacer(1, 6))

    for i, rec in enumerate(analyses[:50]):  # Cap at 50 for PDF size
        sev_col = severity_color(rec.severity_score) if rec.is_malicious else GREEN
        sev_label = severity_label(rec.severity_score) if rec.is_malicious else "SAFE"
        status_col = RED if rec.is_malicious else GREEN
        status_text = "[THREAT DETECTED]" if rec.is_malicious else "[SAFE]"

        prompt_preview = rec.prompt_text[:200] + ("..." if len(rec.prompt_text) > 200 else "")

        header_rows = [
            [
                Paragraph(f"<font color='#{CYAN.hexval()[2:]}'>#{rec.id}</font>  {status_text}", 
                         ParagraphStyle('hdr', parent=styles['Normal'], fontSize=9, textColor=status_col, fontName='Helvetica-Bold')),
                Paragraph(f"{rec.created_at.strftime('%Y-%m-%d %H:%M') if hasattr(rec.created_at, 'strftime') else str(rec.created_at)[:16]}", 
                         ParagraphStyle('time', parent=styles['Normal'], fontSize=8, textColor=MID_GRAY, alignment=TA_RIGHT)),
            ],
        ]
        hdr_t = Table(header_rows, colWidths=[12*cm, 5*cm])
        hdr_t.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), DARK_PANEL),
            ('TOPPADDING', (0, 0), (-1, -1), 6),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
            ('LEFTPADDING', (0, 0), (0, -1), 10),
            ('BOX', (0, 0), (-1, -1), 0.5, BORDER),
        ]))

        detail_data = [
            [Paragraph("PROMPT", label_style), Paragraph(prompt_preview, mono_style)],
            [Paragraph("ATTACK TYPE", label_style), Paragraph(rec.attack_type or "Benign", body_style)],
            [Paragraph("SEVERITY", label_style), Paragraph(f"{sev_label}  ({rec.severity_score:.0f}/100)", 
                ParagraphStyle('sev', parent=body_style, textColor=sev_col))],
            [Paragraph("CONFIDENCE", label_style), Paragraph(f"{rec.confidence*100:.1f}%", body_style)],
        ]
        if rec.explanation:
            detail_data.append([Paragraph("ANALYSIS", label_style), Paragraph(rec.explanation[:300], body_style)])

        detail_t = Table(detail_data, colWidths=[3*cm, 14*cm])
        detail_t.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), DARK_BG),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ('LEFTPADDING', (0, 0), (0, -1), 10),
            ('LEFTPADDING', (1, 0), (1, -1), 8),
            ('BOX', (0, 0), (-1, -1), 0.5, BORDER),
            ('INNERGRID', (0, 0), (-1, -1), 0.25, BORDER),
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ]))

        story.append(KeepTogether([hdr_t, detail_t]))
        story.append(Spacer(1, 8))

    # ─── Footer ───────────────────────────────────────────────────────
    story.append(Spacer(1, 16))
    story.append(HRFlowable(width="100%", thickness=0.5, color=BORDER))
    footer_style = ParagraphStyle('footer', parent=styles['Normal'],
        fontSize=7.5, textColor=MID_GRAY, alignment=TA_CENTER, spaceBefore=6)
    story.append(Paragraph(
        "Generated by SentinelAI - Intelligent Prompt Detection and Defence Framework | Confidential Security Report",
        footer_style
    ))

    doc.build(story)
    buf.seek(0)
    return buf.read()


@router.get("/download")
async def download_report(
    limit: int = 50,
    malicious_only: bool = False,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """Generate and download a PDF forensic audit report."""
    q = select(PromptAnalysis).where(PromptAnalysis.user_id == current_user.id)
    if malicious_only:
        q = q.where(PromptAnalysis.is_malicious == True)
    q = q.order_by(PromptAnalysis.id.desc()).limit(limit)
    result = await db.execute(q)
    analyses = result.scalars().all()

    if not analyses:
        raise HTTPException(status_code=404, detail="No analysis records found to generate report.")

    pdf_bytes = build_pdf_report(list(analyses), current_user, "threat_audit")
    filename = f"sentinelai_report_{datetime.utcnow().strftime('%Y%m%d_%H%M%S')}.pdf"

    return Response(
        content=pdf_bytes,
        media_type="application/pdf",
        headers={"Content-Disposition": f"attachment; filename={filename}"}
    )

@router.get("/download/threats")
async def download_threats_report(
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    """Download PDF report containing only threats."""
    q = (select(PromptAnalysis)
         .where(PromptAnalysis.user_id == current_user.id)
         .where(PromptAnalysis.is_malicious == True)
         .order_by(PromptAnalysis.id.desc())
         .limit(50))
    result = await db.execute(q)
    analyses = result.scalars().all()

    if not analyses:
        raise HTTPException(status_code=404, detail="No threat records found.")

    pdf_bytes = build_pdf_report(list(analyses), current_user, "threats_only")
    filename = f"sentinelai_threats_{datetime.utcnow().strftime('%Y%m%d_%H%M%S')}.pdf"
    return Response(
        content=pdf_bytes,
        media_type="application/pdf",
        headers={"Content-Disposition": f"attachment; filename={filename}"}
    )
